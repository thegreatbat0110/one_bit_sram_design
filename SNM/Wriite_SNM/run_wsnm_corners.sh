#!/bin/bash

CORNERS=("tt" "ss" "ff" "sf" "fs")
TEMPS=("-40" "0" "27" "85")
TEMPLATE="six_t_write_snm.spice"

mkdir -p sim_results_wsnm

for corner in "${CORNERS[@]}"; do
    for temp in "${TEMPS[@]}"; do
        netlist="sim_results_wsnm/wsnm_${corner}_t${temp}.spice"
        output_log="sim_results_wsnm/log_${corner}_t${temp}.log"
        
        echo "Running WSNM for $corner at ${temp}°C..."
        
        # Replace library corner and temperature placeholders
        sed -e "s/__CORNER__/$corner/g" \
            -e "s/__TEMP__/$temp/g" \
            "$TEMPLATE" > "$netlist"
            
        ngspice -b "$netlist" > "$output_log"
        
        # Copy the default output files generated by your netlist to unique names per corner
        if [ -f "dc1_out.txt" ]; then
            cp dc1_out.txt "sim_results_wsnm/dc1_${corner}_t${temp}.txt"
        fi
        if [ -f "dc2_out.txt" ]; then
            cp dc2_out.txt "sim_results_wsnm/dc2_${corner}_t${temp}.txt"
        fi
    done
done

echo "All WSNM simulations and file copying completed!"
